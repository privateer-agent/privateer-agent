#!/usr/bin/env node
// Regenerates extensions/speak-voices.data.ts from the Privateer app's voice table, so
// the terminal's voice picker describes each voice in the same (sourced) words as the
// app's. Run after the app's table changes:
//
//   node scripts/gen-speak-voices.mjs ../treeview/client/constants/voiceProfiles.ts
//
// The app's table is transcribed from each provider's own published voice list (see
// its header for sources); this script only turns its closed vocabulary into English.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/gen-speak-voices.mjs <path to treeview voiceProfiles.ts>");
  process.exit(1);
}

// camelCase vocabulary → words, where splitting on capitals isn't enough.
const WORDS = {
  downToEarth: "down-to-earth",
  easyGoing: "easy-going",
  eLearning: "e-learning",
  ivr: "phone menus",
  latinAmerican: "Latin American",
};
const words = (term) => WORDS[term] ?? term.replace(/([a-z])([A-Z])/g, "$1 $2").toLowerCase();
const accent = (a) => (WORDS[a] ?? a.charAt(0).toUpperCase() + a.slice(1));

const list = (s) => (s ? [...s.matchAll(/'([^']+)'/g)].map((m) => m[1]) : []);
const row = /^\s*'?([A-Za-z0-9_.:-]+)'?:\s*v\(\s*(null|'[a-z]+')\s*,\s*(null|'[a-z]+')\s*,\s*\[([^\]]*)\]\s*(?:,\s*\{([^}]*)\})?\s*\),?/;

const out = {};
for (const line of readFileSync(source, "utf8").split("\n")) {
  const m = row.exec(line);
  if (!m) continue;
  const [, id, gender, age, traits, opts = ""] = m;
  const parts = [];
  if (gender !== "null") parts.push(gender.slice(1, -1));
  if (age !== "null") parts.push(age.slice(1, -1));
  const acc = /accent:\s*'([a-zA-Z]+)'/.exec(opts)?.[1];
  if (acc) parts.push(accent(acc));
  const t = list(traits).map(words);
  if (t.length) parts.push(t.join(", "));
  const grade = /grade:\s*'([^']+)'/.exec(opts)?.[1];
  if (grade) parts.push(`grade ${grade}`);
  const best = list(/bestFor:\s*\[([^\]]*)\]/.exec(opts)?.[1]).map(words);
  if (best.length) parts.push(`for ${best.join(", ")}`);
  if (parts.length) out[id] = parts.join(" · ");
}

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "extensions", "speak-voices.data.ts");
const body = Object.entries(out)
  .map(([id, d]) => `  ${JSON.stringify(id)}: ${JSON.stringify(d)},`)
  .join("\n");
writeFileSync(
  target,
  `// GENERATED by scripts/gen-speak-voices.mjs from the Privateer app's voiceProfiles.ts.\n` +
    `// Do not edit by hand: change the app's table and regenerate. Every entry is the\n` +
    `// provider's own published description of the voice (see that file's sources).\n` +
    `export const VOICE_DESCRIPTIONS: Readonly<Record<string, string>> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(out).length} voice descriptions → ${target}`);
